import { calculateHorizontalMasonryLayout, calculateMasonryLayout } from "/vendor/core/index.js";

const stage = document.querySelector("#stage");
const stageWrap = document.querySelector("#stage-wrap");
const status = document.querySelector("#demo-status");
const controls = ["axis", "distribution", "flow", "cross", "tolerance"].map((id) => document.querySelector(`#${id}`));
const isKorean = document.documentElement.lang === "ko";
let itemCount = 9;

const palette = ["#78b7ff", "#f7c66a", "#c69cff", "#7de0b0", "#ff9a8b", "#8ed6d0"];
function items(axis, bindingSize) {
  return Array.from({ length: itemCount }, (_, index) => ({
    id: `item-${index + 1}`,
    aspectRatio: [4, 0.5, 1, 3, 0.7][index % 5],
    layoutHint: axis === "vertical"
      ? index === 2 ? { columnSpan: 2, preferredColumn: 1 } : index === 5 ? { lockedColumn: 0 } : undefined
      : index === 2 ? { rowSpan: 2, preferredRow: 1 } : index === 5 ? { lockedRow: 0 } : undefined,
    resolvedFootprint: index % 4 === 0
      ? axis === "vertical" ? { height: 150 + index * 8, forWidth: bindingSize } : { width: 210 + index * 8, forHeight: bindingSize }
      : undefined,
  }));
}

function options(axis) {
  const width = Math.max(320, Math.min(940, stageWrap.clientWidth - 8));
  const tolerance = Math.max(0, Number(document.querySelector("#tolerance").value) || 0);
  const common = {
    gap: 12,
    flowDistribution: document.querySelector("#distribution").value,
    flowDirection: document.querySelector("#flow").value,
    crossDirection: document.querySelector("#cross").value,
    flowTolerance: tolerance,
    reservedRegions: [{ laneStart: 1, laneSpan: 1, flowStart: 250, flowSize: 110 }],
  };
  return axis === "vertical"
    ? { ...common, containerWidth: width, minColumnWidth: 150, maxColumns: 4 }
    : { ...common, containerHeight: 360, minRowHeight: 120, maxRows: 3 };
}

function render() {
  const axis = document.querySelector("#axis").value;
  const resolvedOptions = options(axis);
  const provisionalItems = items(axis, 1);
  const provisional = axis === "vertical" ? calculateMasonryLayout(provisionalItems, resolvedOptions) : calculateHorizontalMasonryLayout(provisionalItems, resolvedOptions);
  const bindingSize = axis === "vertical" ? provisional.columnWidth : provisional.rowHeight;
  const layoutItems = items(axis, bindingSize);
  const layout = axis === "vertical" ? calculateMasonryLayout(layoutItems, resolvedOptions) : calculateHorizontalMasonryLayout(layoutItems, resolvedOptions);
  const horizontal = axis === "horizontal";
  stage.className = `stage ${horizontal ? "horizontal" : "vertical"}`;
  stage.style.width = horizontal ? `${Math.max(stageWrap.clientWidth, layout.containerWidth)}px` : "100%";
  stage.style.height = horizontal ? `${layout.containerHeight}px` : `${Math.max(260, layout.containerHeight)}px`;
  stage.replaceChildren(...layout.cells.map((cell, index) => {
    const element = document.createElement("article");
    element.className = "demo-cell";
    element.style.left = `${cell.x}px`;
    element.style.top = `${cell.y}px`;
    element.style.width = `${cell.width}px`;
    element.style.height = `${cell.height}px`;
    element.style.background = `linear-gradient(145deg, ${palette[index % palette.length]}, #151a2a)`;
    const laneLabel = horizontal
      ? isKorean ? `행 ${cell.row} · ${cell.rowSpan}행 차지` : `row ${cell.row} · span ${cell.rowSpan}`
      : isKorean ? `열 ${cell.column} · ${cell.columnSpan}열 차지` : `column ${cell.column} · span ${cell.columnSpan}`;
    element.innerHTML = `<strong>${cell.id}</strong><small>${laneLabel}</small>`;
    return element;
  }));
  status.textContent = isKorean
    ? `${horizontal ? "가로" : "세로"} · 항목 ${layout.cells.length}개 · 진행 범위 ${Math.round(horizontal ? layout.containerWidth : layout.containerHeight)}px · Core 계산 결과`
    : `${axis} · ${layout.cells.length} cells · ${horizontal ? `flow extent ${Math.round(layout.containerWidth)}px` : `flow extent ${Math.round(layout.containerHeight)}px`} · generated by frozen Core`;
}

controls.forEach((control) => control.addEventListener("input", render));
document.querySelector("#add").addEventListener("click", () => { itemCount += 1; render(); });
document.querySelector("#reset").addEventListener("click", () => { itemCount = 9; document.querySelector("#tolerance").value = "0"; render(); });
new ResizeObserver(render).observe(stageWrap);
render();
